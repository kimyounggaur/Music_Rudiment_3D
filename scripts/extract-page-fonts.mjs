// v3 R3 printed-page fonts (CONTRACT_V3 decision 4).
//
//   PRETENDARD_DIR=<unpacked npm pretendard@1.3.9>/package \
//   NOTO_SERIF_CJK=/usr/share/fonts/opentype/noto/NotoSerifCJK-Bold.ttc \
//   node scripts/extract-page-fonts.mjs
//
// Subsets OFL-1.1 fonts to the characters this app can print: every non-ASCII character in
// src/ (book content, lesson feedback and UI strings) plus printable ASCII and a few typographic
// marks. A subset is a Modified Version under the OFL, so it is renamed (condition 3, Reserved
// Font Names): Pretendard → "Book Sans", Noto Serif CJK KR → "Book Serif" (scripts/rename-subset-font.py).
// Requires Python fontTools + brotli (pyftsubset) at generation time only; the WOFF2 outputs,
// their SHA-256 and the character list are committed so builds never need the tools.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, readdirSync, readFileSync, statSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pretendard = process.env.PRETENDARD_DIR;
const notoSerif = process.env.NOTO_SERIF_CJK ?? '/usr/share/fonts/opentype/noto/NotoSerifCJK-Bold.ttc';
if (!pretendard) throw new Error('Set PRETENDARD_DIR to the unpacked pretendard@1.3.9 package directory.');

function sourceFiles(directory) {
  return readdirSync(directory).flatMap(name => {
    const path = join(directory, name);
    if (statSync(path).isDirectory()) return name === 'legacy' ? [] : sourceFiles(path);
    return /\.(ts|tsx)$/.test(name) && !name.endsWith('.generated.ts') ? [path] : [];
  });
}
const characters = new Set();
for (let code = 0x20; code <= 0x7e; code += 1) characters.add(String.fromCodePoint(code));
for (const mark of '·…‘’“”–—×÷½¼¾→←↑↓≤≥%°') characters.add(mark);
for (const file of sourceFiles(join(root, 'src'))) {
  for (const character of readFileSync(file, 'utf8')) {
    const code = character.codePointAt(0);
    if (code > 0x7e && !/\s/.test(character)) characters.add(character);
  }
}
const ordered = [...characters].sort((a, b) => a.codePointAt(0) - b.codePointAt(0)).join('');
const work = mkdtempSync(join(tmpdir(), 'page-fonts-'));
const textFile = join(work, 'characters.txt');
writeFileSync(textFile, ordered, 'utf8');

const outputs = [
  { family: 'Book Sans', style: 'Regular', postscript: 'BookSans-Regular', weight: '400', source: join(pretendard, 'dist/public/static/Pretendard-Regular.otf'), file: 'book-sans-regular.subset.woff2' },
  { family: 'Book Sans', style: 'SemiBold', postscript: 'BookSans-SemiBold', weight: '600', source: join(pretendard, 'dist/public/static/Pretendard-SemiBold.otf'), file: 'book-sans-semibold.subset.woff2' },
  { family: 'Book Serif', style: 'Bold', postscript: 'BookSerif-Bold', weight: '700', source: notoSerif, fontNumber: 1, file: 'book-serif-bold.subset.woff2' },
];
const fontDirectory = join(root, 'public/fonts');
mkdirSync(fontDirectory, { recursive: true });
// Generated files only: never leave a stale subset (or a reserved name) behind.
for (const name of readdirSync(fontDirectory)) if (name.endsWith('.subset.woff2')) rmSync(join(fontDirectory, name));
const records = [];
for (const output of outputs) {
  const target = join(fontDirectory, output.file);
  const args = [output.source, `--text-file=${textFile}`, '--flavor=woff2', `--output-file=${target}`,
    '--layout-features=kern,liga,ccmp,locl,vert,palt', '--no-hinting', '--desubroutinize', '--name-IDs=*', '--name-legacy', '--name-languages=*'];
  if (output.fontNumber !== undefined) args.push(`--font-number=${output.fontNumber}`);
  execFileSync('pyftsubset', args, { stdio: 'inherit' });
  execFileSync('python3', [join(root, 'scripts/rename-subset-font.py'), target, output.family, output.style, output.postscript], { stdio: 'inherit' });
  const bytes = readFileSync(target);
  records.push({ family: output.family, weight: output.weight, url: `/fonts/${output.file}`, bytes: bytes.length,
    sha256: createHash('sha256').update(bytes).digest('hex') });
  process.stdout.write(`${relative(root, target)} ${bytes.length} bytes\n`);
}
rmSync(work, { recursive: true, force: true });

const version = `page-fonts:${records.map(record => record.sha256.slice(0, 8)).join(':')}`;
writeFileSync(join(root, 'src/book/print/pageFonts.generated.ts'), `// Generated by node scripts/extract-page-fonts.mjs. Do not edit.
// Renamed OFL-1.1 subsets: Book Sans (from Pretendard 1.3.9), Book Serif (from Noto Serif CJK KR Bold);
// see public/licenses/book-page-fonts.txt.
export const PAGE_FONT_VERSION = ${JSON.stringify(version)};
export type BundledPageFont = Readonly<{ family: string; weight: string; url: string; bytes: number; sha256: string }>;
export const PAGE_FONTS: readonly BundledPageFont[] = ${JSON.stringify(records, null, 2)};
/** Every character the subsets were built for (non-ASCII taken from src/ at generation time). */
export const PAGE_FONT_CHARACTERS = ${JSON.stringify(ordered)};
`);

const licenseText = (path) => readFileSync(path, 'utf8').trim();
const notoCopyright = '/usr/share/doc/fonts-noto-cjk/copyright';
let notoNotice = 'Noto Serif CJK: Copyright 2017-2022 Adobe (http://www.adobe.com/), with Reserved Font Name \'Source\'. Licensed under the SIL Open Font License, Version 1.1.';
try {
  const text = readFileSync(notoCopyright, 'utf8');
  const match = /Copyright: ([^\n]+Adobe[^\n]*)/.exec(text);
  if (match) notoNotice = `Noto Serif CJK KR Bold (subset): Copyright ${match[1].trim()}. Licensed under the SIL Open Font License, Version 1.1.`;
} catch { /* the default notice above applies */ }
mkdirSync(join(root, 'public/licenses'), { recursive: true });
writeFileSync(join(root, 'public/licenses/book-page-fonts.txt'), `Printed page fonts

Each file is a Modified Version of an SIL Open Font License 1.1 font: a glyph subset compressed
as WOFF2. As OFL condition 3 requires for Reserved Font Names, the subsets carry new names:
  "Book Sans" (Regular 400, SemiBold 600) is derived from Pretendard 1.3.9 (Reserved Font Name "Pretendard").
  "Book Serif" (Bold 700) is derived from Noto Serif CJK KR Bold (Reserved Font Name "Source").
The original copyright, trademark and licence records are kept inside each font file.

1. Pretendard 1.3.9 Regular and SemiBold (npm package "pretendard@1.3.9")
${licenseText(join(pretendard, 'dist/LICENSE.txt'))}

2. ${notoNotice}
The full SIL Open Font License 1.1 text is reproduced in section 1 above and applies equally.
Source: https://github.com/notofonts/noto-cjk

Subset files: ${records.map(record => `${record.url} (${record.bytes} bytes, sha256 ${record.sha256})`).join('; ')}
`);
process.stdout.write(`characters: ${ordered.length}\n`);

/** Reproduce the local font payload from the pinned installed package; no network or font editing. */
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { Buffer } from 'node:buffer';
import { URL } from 'node:url';

const root = new URL('../', import.meta.url);
const pkg = JSON.parse(await readFile(new URL('node_modules/vexflow/package.json', root), 'utf8'));
if (pkg.version !== '5.0.0') throw new Error(`Review font extraction before changing VexFlow ${pkg.version}.`);
const sources = [
  ['bravura', 'Bravura', 'Bravura', 'normal', '5c25278c208ca455dc7c3c0c95d833e134aca6d740a023767af50d0dfa06ef82'],
  ['academico', 'Academico', 'Academico', 'normal', '363caf009818b9cebc7a2644d96b5dc10a20d3b5e557afdb4fb1a9a53d57e329'],
  ['academicobold', 'AcademicoBold', 'Academico', 'bold', '575c2e30fcf7dd9363e49890644b2ed23b6b518c9866aadb5370d470473297b6'],
];
const fonts = [];
for (const [file, symbol, family, weight, expectedHash] of sources) {
  const source = await readFile(new URL(`node_modules/vexflow/build/esm/src/fonts/${file}.js`, root), 'utf8');
  const match = source.match(new RegExp(`^export const ${symbol} = '(data:font/woff2;charset=utf-8;base64,[A-Za-z0-9+/=]+)';\\s*$`));
  if (!match) throw new Error(`Unexpected pinned font export: ${file}`);
  const data = Buffer.from(match[1].split(',')[1], 'base64');
  const sha256 = createHash('sha256').update(data).digest('hex');
  if (data.subarray(0, 4).toString('ascii') !== 'wOF2' || sha256 !== expectedHash) throw new Error(`Font bytes changed: ${file}`);
  fonts.push({ family, weight, dataUrl: match[1], sha256, bytes: data.length });
}
const license = (await readFile(new URL('public/licenses/book-notation-fonts.txt', root), 'utf8')).replace(/\r\n/g, '\n');
const generated = `// Generated by node scripts/extract-notation-fonts.mjs from VexFlow 5.0.0.\n// Unmodified font bytes: OFL-1.1; see public/licenses/book-notation-fonts.txt.\nexport const NOTATION_FONT_VERSION = 'vexflow-5.0.0:bravura-5c25278c:academico-363caf00:academicobold-575c2e30';\nexport type BundledNotationFont = Readonly<{ family: string; weight: string; dataUrl: string; sha256: string; bytes: number }>;\nexport const NOTATION_FONTS: readonly BundledNotationFont[] = ${JSON.stringify(fonts, null, 2)};\nexport const NOTATION_FONT_LICENSE: string = ${JSON.stringify(license)};\n`;
const destination = new URL('src/book/notationFonts.generated.ts', root);
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== generated) throw new Error('Generated notation fonts are stale.');
  console.log('Pinned font payload and license are current.');
} else {
  await writeFile(destination, generated, 'utf8');
  console.log(`Extracted ${fonts.length} unchanged local fonts (${fonts.reduce((n, f) => n + f.bytes, 0)} bytes).`);
}
